#!/usr/bin/env bash
# Build submissions/ and the code zip for Blackboard.
#
# The folder holds copies of existing code only. It keeps the folder names of the repository, so every
# relative path in the copied code resolves inside submissions/ and no file needs an edit. The script
# removes and rebuilds submissions/ each time, so it can be rerun if the code changes.
#
# Run from anywhere in the repository:  bash scripts/build_submission.sh
# It writes submissions/ and STAT3007_G2_code.zip at the repository root.
set -euo pipefail

ROOT=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
DEST="$ROOT/submissions"
ZIP="$ROOT/STAT3007_G2_code.zip"
case "$DEST" in
  */submissions) ;;
  *) echo "build_submission: unexpected destination $DEST" >&2; exit 1 ;;
esac

cd "$ROOT"
rm -rf "$DEST"
mkdir -p "$DEST"
EXCLUDE=(--exclude __pycache__ --exclude .DS_Store)

# The analysis code and its data extract. out/ is regenerated by make_all.py.
mkdir -p "$DEST/report_v2"
rsync -a "${EXCLUDE[@]}" --exclude /out/ report_v2/code/ "$DEST/report_v2/code/"

# Single files are listed one by one, so nothing extra comes along.
copy() {
  for f in "$@"; do
    mkdir -p "$DEST/$(dirname "$f")"
    cp -p "$f" "$DEST/$f"
  done
}

# The environment of the training code.
copy pyproject.toml uv.lock

# The modular addition sweep and the modules it imports, including those imported inside functions.
copy repoduced-code/dataset_sweep.py repoduced-code/ntk_lib.py repoduced-code/RepoducedCode.py \
     repoduced-code/ntk_trace.py repoduced-code/kernel_snapshots.py repoduced-code/dataset_features.py

# ntk_trace.py adds animations/ to sys.path and imports common.kernels.
copy animations/common/__init__.py animations/common/kernels.py

# The scripts between the sweep and extract.py.
copy model_fitting/report_kernel.py model_fitting/report_runs.py

# The MNIST sweep, its loader and its features, the record of how it was launched, and the pilot.
copy mnist/README.md mnist/RUN_SWEEP.md mnist/mnist_sweep.py mnist/mnist_data.py mnist/mnist_features.py \
     mnist/Snakefile mnist/exploration/mnist_pilot.py \
     mnist/exploration/results/mnist_pilot/summary_kumar_b.json \
     mnist/exploration/results/mnist_pilot/mnist_kumarB_a*.json

# The top-level README.
cp scripts/submission_README.md "$DEST/README.md"

# The zip opens to one folder, submissions/.
mkdir -p "$(dirname "$ZIP")"
rm -f "$ZIP"
zip -q -r -X "$ZIP" submissions -x '*/__pycache__/*' '*.DS_Store'

echo "build_submission: $(find "$DEST" -type f | wc -l | tr -d ' ') files in submissions/"
echo "build_submission: $(du -h "$ZIP" | cut -f1) in ${ZIP#"$ROOT"/}"
